import { lazy, type ComponentType, type LazyExoticComponent } from "react";
import { reloadForUpdate } from "./platform/update";

/** Lazy game chunk. A page opened before a new deploy asks for chunks that no longer exist: reload once to update. */
const load = (fn: () => Promise<{ default: ComponentType }>) =>
  lazy(() => fn().catch((err) => (reloadForUpdate() ? new Promise<never>(() => {}) : Promise.reject(err))));

export interface GameEntry {
  id: string;
  name: string;
  tagline: string;
  genre: string;
  /** Has private online tables (two devices joined by a code); listed under the "Online multiplayer" category. */
  online?: boolean;
  /** Square store icon (256px). */
  icon: string;
  /** Wide feature graphic (1024x500) for the showcase hero, when the game has one. */
  feature?: string;
  description: string;
  /** Code-split: a game's code (and Phaser) only downloads when it is opened. */
  component: LazyExoticComponent<ComponentType>;
}

