export const PuttPalCourses = {
  W, H, Par, Names, Holes,
  get Count() { return Holes.length; },

  /** The map for a level (1-based); every second lap is mirrored left-right. m[x][row]. */
  Map(level: number): { map: string[][]; par: number; name: string } {
    const i = (level - 1) % Holes.length;
    const mirror = Math.trunc((level - 1) / Holes.length) % 2 === 1;
    const m: string[][] = Array.from({ length: W }, () => new Array<string>(H));
    for (let row = 0; row < H; row++)
      for (let x = 0; x < W; x++) m[x][row] = Holes[i][row][mirror ? W - 1 - x : x];
    return { map: m, par: Par[i], name: Names[i] };
  },
};
